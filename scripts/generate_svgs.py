#!/usr/bin/env python3
"""Generate the original SVG assets for AI Kaarkhana.

The SVGs under ``assets/`` are generated by this script so that the visual
identity stays consistent and diffs stay reviewable. Edit this file, run it,
and commit both the script change and the regenerated SVGs:

    python3 scripts/generate_svgs.py

Design rules (see assets/README.md):
- Every SVG draws its own dark panel, so it is readable on light and dark pages.
- One palette, one font stack, one icon language (rounded cards, gear mark).
- No external fonts, images or scripts.
"""

from __future__ import annotations

import math
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"

# Palette ------------------------------------------------------------------
BG = "#14172B"        # panel
CARD = "#1E2347"      # card
CARD_HI = "#283061"   # raised card
TEXT = "#F6F2E8"      # primary text (high contrast on BG)
MUTED = "#B9BFDD"     # secondary text
SAFFRON = "#F5A623"   # primary accent
TEAL = "#2CC4B8"      # secondary accent
CORAL = "#FF7A6B"     # alert / red phase
LEAF = "#7BD88F"      # green phase
FONT = "-apple-system, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif"


def svg_open(w: int, h: int, title: str, desc: str) -> list[str]:
    return [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-labelledby="t d">',
        f"<title id=\"t\">{escape(title)}</title>",
        f"<desc id=\"d\">{escape(desc)}</desc>",
        "<defs>",
        '<marker id="arr" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto">'
        f'<path d="M0 0 L10 5 L0 10 z" fill="{SAFFRON}"/></marker>',
        '<pattern id="jaali" width="24" height="24" patternUnits="userSpaceOnUse">'
        f'<path d="M12 4 L20 12 L12 20 L4 12 z" fill="none" stroke="{SAFFRON}" stroke-opacity="0.18" stroke-width="1"/></pattern>',
        "</defs>",
        f'<rect width="{w}" height="{h}" rx="18" fill="{BG}"/>',
        f'<rect width="{w}" height="10" rx="5" fill="url(#jaali)" y="0" opacity="0"/>',
        f'<rect x="0" y="0" width="{w}" height="26" fill="url(#jaali)" clip-path="inset(0 round 18px 18px 0 0)"/>',
        f'<rect x="0" y="{h-4}" width="{w}" height="4" fill="{SAFFRON}" opacity="0.9" clip-path="inset(0 round 0 0 18px 18px)"/>',
    ]


def text(x, y, s, size=16, fill=TEXT, weight=400, anchor="start", extra="") -> str:
    return (
        f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{fill}" '
        f'font-weight="{weight}" text-anchor="{anchor}" {extra}>{escape(s)}</text>'
    )


def card(x, y, w, h, title, lines=(), accent=SAFFRON, fill=CARD, title_size=17, line_size=13.5, num=None) -> list[str]:
    out = [
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="{fill}" stroke="{accent}" stroke-width="1.6"/>',
        f'<rect x="{x}" y="{y+10}" width="5" height="{h-20}" rx="2.5" fill="{accent}"/>',
    ]
    ty = y + 28
    tx = x + 20
    if num is not None:
        out.append(f'<circle cx="{x+26}" cy="{y+26}" r="13" fill="{accent}"/>')
        out.append(text(x + 26, y + 31, str(num), 14, BG, 700, "middle"))
        tx = x + 48
    out.append(text(tx, ty + (3 if num is not None else 0), title, title_size, TEXT, 700))
    ly = ty + 22 + (3 if num is not None else 0)
    for ln in lines:
        out.append(text(x + 20, ly, ln, line_size, MUTED))
        ly += line_size + 6
    return out


def arrow(x1, y1, x2, y2, color=SAFFRON, dashed=False) -> str:
    dash = ' stroke-dasharray="6 5"' if dashed else ""
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{color}" stroke-width="2.2"{dash} '
        'marker-end="url(#arr)"/>'
    )


def curve(d, color=SAFFRON, dashed=False) -> str:
    dash = ' stroke-dasharray="6 5"' if dashed else ""
    return f'<path d="{d}" fill="none" stroke="{color}" stroke-width="2.2"{dash} marker-end="url(#arr)"/>'


def edge_pt(cx, cy, w, h, tx, ty, pad=4):
    """Point where the ray from the rectangle centre (cx, cy) towards (tx, ty) leaves the rectangle."""
    dx, dy = tx - cx, ty - cy
    if dx == 0 and dy == 0:
        return cx, cy
    sx = (w / 2 + pad) / abs(dx) if dx else float("inf")
    sy = (h / 2 + pad) / abs(dy) if dy else float("inf")
    k = min(sx, sy)
    return round(cx + dx * k), round(cy + dy * k)


def heading(w, title, subtitle) -> list[str]:
    return [text(40, 62, title, 28, TEXT, 800), text(40, 88, subtitle, 15, MUTED)]


def gear(cx, cy, r, teeth=10, color=SAFFRON, inner=BG) -> list[str]:
    out = [f'<g transform="translate({cx} {cy})">']
    tw, th = r * 0.30, r * 0.30
    for i in range(teeth):
        ang = 360 / teeth * i
        out.append(
            f'<rect x="{-tw/2:.2f}" y="{-r - th*0.55:.2f}" width="{tw:.2f}" height="{th*1.1:.2f}" rx="{tw*0.2:.2f}" '
            f'fill="{color}" transform="rotate({ang:.1f})"/>'
        )
    out.append(f'<circle r="{r}" fill="{color}"/>')
    out.append(f'<circle r="{r*0.62:.2f}" fill="{inner}"/>')
    d = r * 0.36
    out.append(f'<path d="M0 {-d:.2f} L{d:.2f} 0 L0 {d:.2f} L{-d:.2f} 0 z" fill="{TEAL}"/>')
    out.append("</g>")
    return out


def write(rel: str, parts: list[str]) -> None:
    path = ASSETS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts + ["</svg>"]) + "\n", encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


