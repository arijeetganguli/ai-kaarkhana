#!/usr/bin/env python3
"""Build the skill registry from the front matter of every skills/*/SKILL.md.

Outputs
    skills/REGISTRY.md    human readable catalogue (by activity, difficulty, framework)
    skills/registry.json  machine readable catalogue

Usage
    python scripts/build_registry.py            write both files
    python scripts/build_registry.py --check    exit 1 if the files are out of date

Only the Python standard library is used. The front matter parser understands the
small subset of YAML that skills use: top level `key: value` pairs and one nested
`metadata:` mapping.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"

ACTIVITY_ORDER = [
    ("requirements", "Requirements"),
    ("planning", "Planning and exploration"),
    ("testing", "Testing"),
    ("quality", "Code quality and correctness"),
    ("security", "Security"),
    ("performance", "Performance"),
    ("debugging", "Debugging and regression"),
    ("architecture", "Architecture and design"),
    ("review", "Review and pull requests"),
    ("documentation", "Documentation"),
]
DIFFICULTY_ORDER = ["beginner", "intermediate", "advanced"]


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_front_matter(text, path):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: missing front matter")
    try:
        end = lines[1:].index("---") + 1
    except ValueError:
        raise ValueError(f"{path}: front matter is not closed") from None
    data = {}
    current = None
    for raw in lines[1:end]:
        if not raw.strip():
            continue
        indented = raw.startswith("  ")
        key, _, value = raw.strip().partition(":")
        if indented:
            if current is None:
                raise ValueError(f"{path}: indented line without a parent: {raw!r}")
            data[current][key.strip()] = unquote(value)
        elif value.strip() == "":
            current = key.strip()
            data[current] = {}
        else:
            current = None
            data[key.strip()] = unquote(value)
    return data


def first_sentence(text):
    text = " ".join(text.split())
    cut = text.find(". ")
    return text[: cut + 1] if cut != -1 else text


def load_skills():
    skills = []
    for skill_md in sorted(SKILLS.glob("*/SKILL.md")):
        data = parse_front_matter(skill_md.read_text(encoding="utf-8"), skill_md)
        folder = skill_md.parent.name
        name = data.get("name")
        if name != folder:
            raise ValueError(f"{skill_md}: name {name!r} does not match folder {folder!r}")
        if not data.get("description"):
            raise ValueError(f"{skill_md}: description is required")
        meta = data.get("metadata", {})
        for required in ("activity", "difficulty", "frameworks", "version"):
            if required not in meta:
                raise ValueError(f"{skill_md}: metadata.{required} is required")
        title = next(
            (ln[2:].strip() for ln in skill_md.read_text(encoding="utf-8").splitlines() if ln.startswith("# ")),
            name,
        )
        frameworks = [f.strip() for f in meta["frameworks"].split(",") if f.strip()]
        skills.append(
            {
                "name": name,
                "title": title,
                "description": data["description"],
                "summary": first_sentence(data["description"]),
                "path": f"skills/{folder}/SKILL.md",
                "activity": meta["activity"],
                "difficulty": meta["difficulty"],
                "frameworks": frameworks,
                "version": meta["version"],
                "license": data.get("license", ""),
            }
        )
    return skills


def link(skill):
    return f"[{skill['title']}]({skill['name']}/SKILL.md)"


def build_markdown(skills):
    out = []
    out.append("# Skill registry")
    out.append("")
    out.append("> Generated by `scripts/build_registry.py` from the front matter of each `SKILL.md`. Do not edit by hand: change the skill and re-run the script. CI checks that this file is current.")
    out.append("")
    out.append(f"**{len(skills)} skills.** Find one by what you are doing (activity), how experienced you are (difficulty) or the tooling it assumes (framework). The same data is available as [`registry.json`](registry.json).")
    out.append("")
    out.append("## All skills")
    out.append("")
    out.append("| Skill | What it does | Activity | Difficulty | Frameworks |")
    out.append("| --- | --- | --- | --- | --- |")
    for s in sorted(skills, key=lambda x: x["title"].lower()):
        out.append(f"| {link(s)} | {s['summary']} | {s['activity']} | {s['difficulty']} | {', '.join(s['frameworks'])} |")
    out.append("")
    out.append("## By engineering activity")
    out.append("")
    known = {a for a, _ in ACTIVITY_ORDER}
    for key, label in ACTIVITY_ORDER:
        group = [s for s in skills if s["activity"] == key]
        if not group:
            continue
        out.append(f"### {label}")
        out.append("")
        for s in sorted(group, key=lambda x: x["title"].lower()):
            out.append(f"- {link(s)} ({s['difficulty']}): {s['summary']}")
        out.append("")
    other = [s for s in skills if s["activity"] not in known]
    if other:
        out.append("### Other")
        out.append("")
        for s in sorted(other, key=lambda x: x["title"].lower()):
            out.append(f"- {link(s)} ({s['difficulty']}): {s['summary']}")
        out.append("")
    out.append("## By difficulty")
    out.append("")
    out.append("Difficulty describes how much engineering judgement the skill needs from the person using it, not how long it takes.")
    out.append("")
    for d in DIFFICULTY_ORDER:
        group = [s for s in skills if s["difficulty"] == d]
        if not group:
            continue
        out.append(f"### {d.capitalize()}")
        out.append("")
        for s in sorted(group, key=lambda x: x["title"].lower()):
            out.append(f"- {link(s)} ({s['activity']})")
        out.append("")
    out.append("## By language and framework")
    out.append("")
    out.append("Skills are tool agnostic. The framework column names the test or API tooling that the skill's examples assume; `any` means it applies regardless.")
    out.append("")
    fw = {}
    for s in skills:
        for f in s["frameworks"]:
            fw.setdefault(f, []).append(s)
    specific = sorted((f for f in fw if f.lower() != "any"), key=str.lower)
    for f in specific + (["any"] if "any" in fw else []):
        label = "Any language or framework" if f == "any" else f
        out.append(f"### {label}")
        out.append("")
        for s in sorted(fw[f], key=lambda x: x["title"].lower()):
            out.append(f"- {link(s)}")
        out.append("")
    out.append("## Recommended starting set")
    out.append("")
    out.append("If you adopt only a few skills, start with these. They cover the failure modes that cause most AI assisted defects.")
    out.append("")
    starter = ["requirement-analyst", "edge-case-hunter", "tdd-engineer", "defensive-programming-reviewer", "pr-readiness-reviewer"]
    by_name = {s["name"]: s for s in skills}
    for n in starter:
        if n in by_name:
            s = by_name[n]
            out.append(f"1. {link(s)}: {s['summary']}")
    out.append("")
    out.append("## Using a skill")
    out.append("")
    out.append("See [skills/README.md](README.md) for how to invoke a skill in your assistant, and [tools](../tools/README.md) for tool specific setup.")
    out.append("")
    return "\n".join(out)


def build_json(skills):
    payload = {
        "schema": "ai-kaarkhana/skill-registry/1",
        "count": len(skills),
        "skills": [
            {k: s[k] for k in ("name", "title", "description", "path", "activity", "difficulty", "frameworks", "version", "license")}
            for s in sorted(skills, key=lambda x: x["name"])
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def main(argv):
    check = "--check" in argv
    skills = load_skills()
    targets = {SKILLS / "REGISTRY.md": build_markdown(skills), SKILLS / "registry.json": build_json(skills)}
    stale = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if check:
            if current != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(content if content.endswith("\n") else content + "\n", encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if check:
        if stale:
            print("registry is out of date: " + ", ".join(map(str, stale)) + "\nrun: python scripts/build_registry.py")
            return 1
        print(f"registry is current ({len(skills)} skills)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
