#!/usr/bin/env python3
"""Generate and install tool specific adapters from the canonical, tool agnostic sources.

Canonical sources (edit these)
    skills/<name>/SKILL.md                 skills
    prompts/<category>/<id>.md             prompts
    tools/generic_agents/principles.md     shared engineering principles

Generated in this repository (do not edit by hand)
    .github/skills/<name>/SKILL.md         copy of each skill, links adjusted for the new depth
    .github/prompts/<id>.prompt.md         one prompt file per library prompt
    the marker delimited principles block inside AGENTS.md and .github/copilot-instructions.md

Usage
    python scripts/sync_adapters.py                    regenerate everything in this repository
    python scripts/sync_adapters.py --check            exit 1 if generated files are out of date
    python scripts/sync_adapters.py install --target T --dest DIR [--prompts] [--force]

    T is one of: github-copilot, cursor, claude-code, generic

Install writes into another project:
    github-copilot  .github/skills/, .github/copilot-instructions.md block, optional .github/prompts/
    cursor          .cursor/skills/, .cursor/rules/ai-kaarkhana-principles.mdc
    claude-code     .claude/skills/, CLAUDE.md block
    generic         .agents/skills/, AGENTS.md block

Installed skills have links to this repository's handbook, prompts and workflows turned into plain
text, because those files do not exist in the destination project. Links between skills are kept.

Only the Python standard library is used.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
PROMPTS = ROOT / "prompts"
PRINCIPLES = ROOT / "tools" / "generic_agents" / "principles.md"

BEGIN = "<!-- BEGIN ai-kaarkhana principles: generated by scripts/sync_adapters.py from tools/generic_agents/principles.md. Edit the source, not this block. -->"
END = "<!-- END ai-kaarkhana principles -->"

INSTALL_BEGIN = "<!-- BEGIN ai-kaarkhana principles: installed by scripts/sync_adapters.py. Re-run the installer to update this block. -->"

TARGETS = {
    "github-copilot": {"skills": ".github/skills"},
    "cursor": {"skills": ".cursor/skills"},
    "claude-code": {"skills": ".claude/skills"},
    "generic": {"skills": ".agents/skills"},
}

LINK_RE = re.compile(r"\[([^\]]+)\]\((\.\./\.\./[^)]*)\)")


# --------------------------------------------------------------------------- helpers
def read(path):
    return Path(path).read_text(encoding="utf-8")


def principles_text():
    return read(PRINCIPLES).strip() + "\n"


def skill_dirs():
    return sorted(p.parent for p in SKILLS.glob("*/SKILL.md"))


def rewrite_for_github_skills(text):
    """skills/<n>/SKILL.md -> .github/skills/<n>/SKILL.md : one directory deeper."""
    return text.replace("](../../", "](../../../")


def strip_repo_links(text):
    """For installs into other projects: links that leave the skills folder become plain text."""
    return LINK_RE.sub(lambda m: m.group(1), text)


def block(content, begin=BEGIN):
    return f"{begin}\n{content.rstrip()}\n{END}\n"


def upsert_block(path, content, begin, heading):
    """Insert or replace the marker block in `path`; create the file with `heading` if missing."""
    path = Path(path)
    new_block = block(content, begin)
    if path.exists():
        text = read(path)
        pattern = re.compile(r"<!-- BEGIN ai-kaarkhana principles.*?-->\n.*?<!-- END ai-kaarkhana principles -->\n", re.S)
        if pattern.search(text):
            updated = pattern.sub(lambda _m: new_block, text, count=1)
        else:
            updated = text.rstrip() + "\n\n" + new_block
    else:
        updated = f"{heading}\n\n{new_block}"
    return updated


def extract_block(text):
    m = re.search(r"<!-- BEGIN ai-kaarkhana principles.*?-->\n(.*?)<!-- END ai-kaarkhana principles -->\n", text, re.S)
    return m.group(1) if m else None


# --------------------------------------------------------------------------- prompts
def parse_prompt(path):
    text = read(path)
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"')
    body = text[m.end():]
    problem = re.search(r"## Problem it solves\n\n(.*?)\n\n", body, re.S)
    section = re.search(r"## Prompt\n(.*?)(?=\n## )", body, re.S)
    if not section:
        raise ValueError(f"{path}: missing Prompt section")
    fence = re.search(r"```text\n(.*?)\n```", section.group(1), re.S)
    if not fence:
        raise ValueError(f"{path}: missing ```text block in Prompt section")
    return {
        "id": meta["id"],
        "title": meta["title"],
        "category": meta["category"],
        "problem": " ".join(problem.group(1).split()) if problem else meta["title"],
        "prompt": fence.group(1),
    }


def render_prompt_file(info, link_prefix):
    """link_prefix is the relative path from the generated file to the repository root, or None."""
    desc = f"{info['title']}: {info['problem']}".replace('"', "'")
    header = f'---\ndescription: "{desc}"\n---\n'
    lines = [
        header,
        f"{info['prompt']}\n",
    ]
    if link_prefix is not None:
        lines.append(f"\n---\nGenerated from [prompts/{info['category']}/{info['id']}.md]({link_prefix}prompts/{info['category']}/{info['id']}.md) by scripts/sync_adapters.py. Replace any [BRACKETED PLACEHOLDER] before sending. Validate the answer with the steps in the source file.\n")
    return "".join(lines)


def all_prompts():
    out = []
    for p in sorted(PROMPTS.glob("*/*.md")):
        if p.name.lower() == "readme.md":
            continue
        out.append(parse_prompt(p))
    return out


# --------------------------------------------------------------------------- expected state of this repository
def expected_repo_files():
    files = {}
    for d in skill_dirs():
        files[ROOT / ".github" / "skills" / d.name / "SKILL.md"] = rewrite_for_github_skills(read(d / "SKILL.md"))
    for info in all_prompts():
        files[ROOT / ".github" / "prompts" / f"{info['id']}.prompt.md"] = render_prompt_file(info, "../../")
    principles = principles_text()
    for path, heading in ((ROOT / "AGENTS.md", None), (ROOT / ".github" / "copilot-instructions.md", None)):
        if not path.exists():
            raise SystemExit(f"{path.relative_to(ROOT)} must exist and contain the marker block; create it first")
        files[path] = upsert_block(path, principles, BEGIN, "")
    return files


def stale_generated():
    stale = []
    skills_dir = ROOT / ".github" / "skills"
    if skills_dir.exists():
        names = {d.name for d in skill_dirs()}
        for child in skills_dir.iterdir():
            if child.is_dir() and child.name not in names:
                stale.append(child)
    prompts_dir = ROOT / ".github" / "prompts"
    if prompts_dir.exists():
        ids = {p["id"] + ".prompt.md" for p in all_prompts()}
        for child in prompts_dir.glob("*.prompt.md"):
            if child.name not in ids:
                stale.append(child)
    return stale


def cmd_sync(check):
    expected = expected_repo_files()
    drift = []
    for path, content in expected.items():
        current = read(path) if path.exists() else None
        if current != content:
            drift.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    stale = stale_generated()
    if check:
        if drift or stale:
            for p in drift:
                print(f"out of date: {p.relative_to(ROOT)}")
            for p in stale:
                print(f"stale (no canonical source): {p.relative_to(ROOT)}")
            print("run: python scripts/sync_adapters.py")
            return 1
        print(f"adapters are current ({len(expected)} generated files)")
        return 0
    for p in stale:
        print(f"stale (no canonical source), remove manually: {p.relative_to(ROOT)}")
    print(f"synced {len(expected)} files ({len(drift)} changed)")
    return 0


# --------------------------------------------------------------------------- install
def cmd_install(target, dest, with_prompts, force):
    dest = Path(dest).expanduser().resolve()
    if not dest.is_dir():
        print(f"destination {dest} is not a directory")
        return 2
    cfg = TARGETS[target]
    written, skipped = [], []

    def put(path, content):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)

    for d in skill_dirs():
        out = dest / cfg["skills"] / d.name / "SKILL.md"
        if out.exists() and not force:
            skipped.append(out)
            continue
        put(out, strip_repo_links(read(d / "SKILL.md")))

    principles = principles_text()
    if target == "github-copilot":
        path = dest / ".github" / "copilot-instructions.md"
        put(path, upsert_block(path, principles, INSTALL_BEGIN, "# Copilot instructions"))
        if with_prompts:
            for info in all_prompts():
                out = dest / ".github" / "prompts" / f"{info['id']}.prompt.md"
                if out.exists() and not force:
                    skipped.append(out)
                    continue
                put(out, render_prompt_file(info, None))
    elif target == "cursor":
        rule = dest / ".cursor" / "rules" / "ai-kaarkhana-principles.mdc"
        if rule.exists() and not force:
            skipped.append(rule)
        else:
            put(rule, "---\ndescription: Engineering principles for AI assisted work\nalwaysApply: true\n---\n\n" + principles)
    elif target == "claude-code":
        path = dest / "CLAUDE.md"
        put(path, upsert_block(path, principles, INSTALL_BEGIN, "# Project instructions"))
    elif target == "generic":
        path = dest / "AGENTS.md"
        put(path, upsert_block(path, principles, INSTALL_BEGIN, "# Agent instructions"))

    if with_prompts and target != "github-copilot":
        print("note: --prompts only applies to github-copilot (prompt files); copy prompts/ manually for other tools")
    for p in written:
        print(f"wrote   {p}")
    for p in skipped:
        print(f"skipped {p} (exists; use --force to overwrite)")
    print(f"done: {len(written)} written, {len(skipped)} skipped")
    return 0


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify generated files are current; change nothing")
    sub = parser.add_subparsers(dest="command")
    inst = sub.add_parser("install", help="install adapters into another project")
    inst.add_argument("--target", required=True, choices=sorted(TARGETS))
    inst.add_argument("--dest", required=True)
    inst.add_argument("--prompts", action="store_true", help="also install prompt files (github-copilot only)")
    inst.add_argument("--force", action="store_true", help="overwrite existing skill and rule files")
    args = parser.parse_args(argv)
    if args.command == "install":
        return cmd_install(args.target, args.dest, args.prompts, args.force)
    return cmd_sync(args.check)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
